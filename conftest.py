r"""
pytest 全局配置
================================================================

这个文件的名字是固定的（conftest.py），pytest 会自动找到并加载它，
不需要你 import。它常用来放"所有测试都要用的东西"，比如：

    - 通用的 fixture（测试用的公共数据）
    - 全局的设置、钩子函数
    - 这里我们用它来修一个 Windows 特有的编码问题

--------------------------------------------------------------------
为什么需要这个文件？
--------------------------------------------------------------------
Windows 上 Python 把输出重定向到管道/文件时，默认会用系统区域编码（GBK），
于是 pytest 打印的中文测试名和报错信息会变成乱码：

    memory.add("user", f"���ǵ� {i} ����Ϣ")

这会让调试变得极其痛苦（因为你看不出测试到底在测什么）。

下面这几行强制把标准输出和标准错误都改成 UTF-8。
放在 conftest.py 里，好处是**你什么都不用做**，
直接跑 pytest 就是正常的，不需要每次记得加 -X utf8 参数。
"""

import sys

for _stream in (sys.stdout, sys.stderr):
    # 不是所有环境都有 reconfigure（比如某些 IDE 的假流对象），所以要判断
    if hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8")
        except (ValueError, OSError):
            # 极少数情况下流已经关闭或不支持，忽略即可，不影响测试运行
            pass
